    # Since they are not, it will log instructions for the user.
    print("Live merge mode requested.")
    if not class_src or not os.path.exists(class_src):
        print(f"Error: Source classification folder '{class_src}' not found. Cannot merge classification.")
    if not seg_src or not os.path.exists(seg_src):
        print(f"Error: Source segmentation folder '{seg_src}' not found. Cannot merge segmentation.")
    print("Switching back to simulation mode to create dataset profile report...")
    simulate_merge()

